  updateTechAnimation(state,0,0,1/60,characterSprite('don'));
  state.special=8;
  updateTechAnimation(state,0,0,1/60,characterSprite('don'));
  assert.equal(state.vfxClock,1/60,'clock restarts at frame 0 on activation');
  state.special=0;
  updateTechAnimation(state,0,0,1/60,characterSprite('don'));
